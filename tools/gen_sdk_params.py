#!/usr/bin/env python3
"""vst/params.json -> src/sdk/params_gen.h: the parameter table of the SDK front end (src/sdk/AcidPlugin.cpp).
Order = vst/params.json = vst/params.lock (checked): the VST parameter index saved projects and skins bind to. Append only.
(The wrapper build's ten pop-up flags "<key>__open" after the engine parameters are replaced by ONE UI-only "ui_open".)"""
import json, os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst/params.json")))["params"]
lock = [l.strip() for l in open(os.path.join(ROOT, "vst/params.lock")) if l.strip()]
keys = [p["key"] for p in P]
if keys[:len(lock)] != lock:
    raise SystemExit("params.json no longer starts with params.lock: the order is frozen (append only)")
# flags: 1 momentary, 4 float value, 8 choice, 16 UI only, 32 pushed (the engine changes it behind the host's back: edit cells, Chain
# readout, Blend), 64 read-only (the engine owns it: running lights, Chain readout), 128 edit cell (never applied while a state loads)
out = ["/* generated by tools/gen_sdk_params.py: do not edit. One row per parameter, in the frozen VST order. */", "#pragma once",
       "enum { kMomentary = 1, kFloat = 4, kChoice = 8, kUi = 16, kPushed = 32, kReadOnly = 64, kEditCell = 128 };",
       "struct PSpec { const char *key, *name; float min, max, def; int flags; const char *const *choices; int nchoices; };", ""]
rows = []
for i, p in enumerate(P):
    k = p["key"]
    fl, ch, n = 0, "nullptr", 0
    if "options" in p:
        fl |= 8
        opts = p["options"]
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in opts)))
        ch, n = "ch_%d" % i, len(opts)
        lo, hi, d = 0, len(opts) - 1, opts.index(p["default"])
    else:
        lo, hi, d = p["min"], p["max"], p["default"]
        if lo != int(lo) or hi != int(hi) or d != int(d): fl |= 4
    if p.get("momentary"): fl |= 1
    if re.match(r"^[ab]_run$", k): d = 0   # derived: the engine's idle value is not a column
    cell = re.match(r"^[ab]_(e\d+_|edit_bar$)", k) is not None
    if cell: fl |= 32 | 128
    if k in ("blend", "chain_view"): fl |= 32
    if re.match(r"^[ab]_run$", k) or k == "chain_view": fl |= 32 | 64
    rows.append('    {%s, %s, %s, %s, %s, %d, %s, %d},' % (json.dumps(k), json.dumps(p["name"]), repr(float(lo)) + "f", repr(float(hi)) + "f", repr(float(d)) + "f", fl, ch, n))
rows.append('    {"ui_open", "POPUP", 0.0f, 96.0f, 0.0f, 16, nullptr, 0},   // UI only (kUi): which drawn pick-list is open; appended last, not an engine key')
out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};", "static const int kNumParams = %d;" % (len(P) + 1), "static const int kUiParam = %d;" % len(P), ""]
open(os.path.join(ROOT, "src/sdk/params_gen.h"), "w").write("\n".join(out))
print("src/sdk/params_gen.h: %d params" % len(P))
